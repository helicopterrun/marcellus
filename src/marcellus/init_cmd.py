"""`fsc init`: write a sidecar.yml by finding Frigate's settings and confirming them.

Order of authority for every value: a command-line flag, then what is found
(Frigate's API and config.yml, see `frigate_discovery`), then what an existing
config file already says (a re-run keeps it and offers it as the default), then
the built-in default. Flags are final and never asked about; everything else is
shown once for a yes/no confirmation, and only a "no" walks through the values
one by one. Nothing here writes to Frigate's config or files.

The optional push step (`init_push`) writes the MQTT broker settings into
`sidecar.yml` and the password only into an env file.
"""

from __future__ import annotations

import contextlib
import copy
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import typer
import yaml

from marcellus import frigate_discovery as fd
from marcellus import init_push as ip

HEADER = (
    "# Generated by `fsc init`. All other settings keep their defaults --\n"
    "# see config/sidecar.example.yml for the full annotated reference.\n"
    "# frigate.verify_tls: false skips the TLS certificate check for Frigate only\n"
    "# (its sign-in port uses a self-signed certificate by default).\n"
    "# The MQTT password is never written here: it lives in an env file as\n"
    '# MARCELLUS_PUSH__MQTT_PASSWORD (see the guide\'s "Set up push" page).\n'
)


@dataclass
class InitOptions:
    output: str
    frigate_url: str | None = None
    proxy_url: str | None = None
    frigate_config: str | None = None
    frigate_db: str | None = None
    recordings_path: str | None = None
    sidecar_db: str | None = None
    bind_host: str | None = None
    bind_port: int | None = None
    non_interactive: bool = False
    force: bool = False
    env_file: str | None = None
    enable_push: bool = False
    mqtt_host: str | None = None
    mqtt_port: int | None = None
    mqtt_user: str | None = None
    mqtt_password_file: str | None = None


def _echo(text: str = "", *, err: bool = False) -> None:
    typer.echo(text, err=err)


def _load_existing(path: Path) -> dict[str, Any]:
    """The current config as a mapping ({} when it is not usable)."""
    try:
        data = yaml.safe_load(path.read_text())
    except (OSError, yaml.YAMLError):
        return {}
    return data if isinstance(data, dict) else {}


def _sub(cfg: dict[str, Any], key: str) -> dict[str, Any]:
    value = cfg.get(key)
    return value if isinstance(value, dict) else {}


def _default_signin_url(base_url: str, frigate_defaults: Any) -> str:
    """Frigate's signed-in origin on the same host as `base_url`.

    https, because Frigate serves port 8971 over TLS by default; `fsc init`
    probes it and corrects the scheme if that host says otherwise.
    """
    from urllib.parse import urlsplit

    default = str(frigate_defaults.proxy_base_url)
    if base_url == frigate_defaults.base_url:
        return default
    try:
        host = urlsplit(base_url).hostname
    except ValueError:
        return default
    if not host:
        return default
    if ":" in host:  # IPv6 literal
        host = f"[{host}]"
    return f"https://{host}:8971"


def check_signin_port(
    url: str, *, interactive: bool, keep_trust: bool = False
) -> tuple[str, bool, list[str]]:
    """Probe Frigate's signed-in port; return `(proxy_base_url, verify_tls,
    warnings)`.

    Fixes the scheme when the port answers in the other one and, for a
    certificate this machine does not trust (Frigate's self-signed default),
    asks whether to trust it (interactive) or keeps the strict default and
    returns a warning naming the setting (non-interactive). `keep_trust` (an
    existing config already says `verify_tls: false`) makes "trust" the answer
    that Enter gives and that a non-interactive re-run keeps. `warnings` are
    printed after the file is written; `{path}` in them is the output path.
    A probe that gets no answer only adds a note: init never fails or hangs
    on it.
    """
    from marcellus import frigate_tls

    probe = frigate_tls.probe_signin_port_bounded(url)
    scheme = url.split("://", 1)[0].lower() if "://" in url else ""
    if probe.scheme is None:
        _echo(
            f"⚠ Could not check Frigate's sign-in port at {url} ({probe.detail}). "
            "If sign-in fails later with a certificate error, see `frigate.verify_tls` "
            "in the guide's Troubleshooting page.",
            err=True,
        )
        return url, not keep_trust, []
    if probe.scheme != scheme:
        fixed = frigate_tls.with_scheme(url, probe.scheme)
        _echo(f"• Frigate's sign-in port speaks {probe.scheme.upper()}: using {fixed}")
        url = fixed
    if probe.scheme == "http":
        _echo(f"✓ Frigate's sign-in port answers over plain HTTP at {url}")
        return url, True, []
    if probe.trusted:
        _echo(f"✓ Frigate's sign-in port at {url} has a trusted certificate")
        return url, True, []
    if probe.trusted is None:
        return (
            url,
            not keep_trust,
            [
                f"⚠ Frigate's sign-in port at {url} speaks HTTPS but did not complete a "
                "connection. If Marcellus cannot reach it, see `frigate.verify_tls` in {path}."
            ],
        )
    if interactive:
        _echo(
            f"Frigate's sign-in port at {url} uses a TLS certificate this machine does not "
            "trust (Frigate makes a self-signed one by default).\n"
            "Trusting it turns off certificate checks for Marcellus's connections to "
            "Frigate only: fine on a home network, but it gives up proof that the other "
            "end really is your Frigate."
        )
        trust_default = probe.private_address or keep_trust
        if typer.confirm("Trust Frigate's certificate?", default=trust_default):
            _echo("✓ Writing frigate.verify_tls: false")
            return url, False, []
    elif keep_trust:
        _echo("• Keeping frigate.verify_tls: false from your existing config")
        return url, False, []
    return (
        url,
        True,
        [
            f"⚠ Frigate's sign-in port at {url} uses a TLS certificate this machine does not "
            "trust (Frigate makes a self-signed one by default), so Marcellus cannot reach it "
            "yet. Either set `frigate.verify_tls: false` in {path} (fine on a home network) "
            "or turn TLS off in Frigate (`tls: enabled: false`) and use http://."
        ],
    )


# -- what was found ------------------------------------------------------------------


def describe(facts: fd.FrigateFacts, base_url: str) -> list[str]:
    """Plain-language summary lines of what discovery found."""
    lines: list[str] = []
    # "0.18.2-cfa08c5" is the version plus a build hash; show the version.
    ver = f"Frigate {facts.version.split('-')[0]}" if facts.version else "Frigate"
    bits = [f"{ver} at {base_url}" if facts.api_ok else f"{ver} (not answering at {base_url})"]
    if facts.cameras is not None:
        bits.append(f"{facts.cameras} camera{'s' if facts.cameras != 1 else ''}")
    if facts.auth_enabled is not None:
        bits.append(f"sign-in {'on' if facts.auth_enabled else 'off'}")
    if facts.tls_enabled is not None:
        bits.append(f"TLS {'on' if facts.tls_enabled else 'off'}")
    lines.append(", ".join(bits))
    if facts.config_file is not None:
        if facts.file_verified is None:
            how = "not checked against a running Frigate"
        elif facts.file_verified:
            how = "matches the running Frigate"
        else:
            how = "does NOT match the running Frigate"
        lines.append(f"config file: {facts.config_file} ({how})")
    m = facts.mqtt
    if facts.found_anything:
        if not m.enabled:
            lines.append("MQTT: off in Frigate (push alerts need it)")
        elif m.host:
            who = f" as user {m.user}" if m.user else ""
            login = " (a password is set)" if m.needs_login and not m.user else ""
            port = m.port or fd.FRIGATE_DEFAULT_MQTT_PORT
            lines.append(f"MQTT: broker at {m.host}:{port}{who}{login}")
        else:
            lines.append("MQTT: on, but the broker address is a placeholder or missing")
    return lines


# -- the main flow --------------------------------------------------------------------


@dataclass
class _Item:
    key: str
    label: str
    value: str
    #: flag | found | existing | env | default | ask
    origin: str


def _check_dir_note(rec_check: fd.RecordingsCheck) -> str:
    return f"{rec_check.path} {rec_check.message}"


def run_init(o: InitOptions) -> None:
    from marcellus import frigate_tls
    from marcellus.config import FrigateSection, Settings, SidecarSection

    interactive = not o.non_interactive
    frigate_defaults = FrigateSection()
    sidecar_defaults = SidecarSection()

    out_path = Path(o.output)
    existing: dict[str, Any] = {}
    if out_path.exists():
        if not o.force:
            _echo(f"{out_path} already exists; use --force to overwrite.", err=True)
            raise typer.Exit(code=1)
        existing = _load_existing(out_path)
    ex_f, ex_s, ex_p = _sub(existing, "frigate"), _sub(existing, "sidecar"), _sub(existing, "push")

    def ask(label: str, flag: str | int | None, default: str) -> str:
        if flag is not None:
            return str(flag)
        if not interactive:
            return default
        return str(typer.prompt(label, default=default))

    base_url = ask(
        "Frigate API URL (unauthenticated origin)",
        o.frigate_url,
        str(ex_f.get("base_url") or frigate_defaults.base_url),
    )
    default_signin = (
        str(ex_f["proxy_base_url"])
        if ex_f.get("proxy_base_url") and ex_f.get("base_url") == base_url
        else _default_signin_url(base_url, frigate_defaults)
    )
    signin_url = ask(
        "Frigate AUTHENTICATED origin (usually port 8971)", o.proxy_url, default_signin
    )
    late_warnings: list[str] = []
    verify_tls = True
    keep_trust = ex_f.get("verify_tls") is False
    if signin_url != frigate_defaults.proxy_base_url:
        signin_url, verify_tls, late_warnings = check_signin_port(
            signin_url, interactive=interactive, keep_trust=keep_trust
        )

    # -- find Frigate's own settings ------------------------------------------------
    ex_config_path = ex_f.get("config_path")
    hint = o.frigate_config or (str(ex_config_path) if ex_config_path else None)
    facts = fd.discover(base_url, verify_tls=verify_tls, config_hint=hint)
    if facts.found_anything:
        _echo("Found Frigate's settings:")
        for line in describe(facts, base_url):
            _echo(f"  {line}")
    for note in facts.notes:
        _echo(f"⚠ {note}", err=True)

    # -- propose every value --------------------------------------------------------
    env = os.environ
    items: dict[str, _Item] = {}

    def propose(key: str, label: str, flag: str | None, candidates: list[tuple[str, str]]) -> None:
        if flag is not None:
            items[key] = _Item(key, label, flag, "flag")
            return
        for origin, value in candidates:
            if value:
                items[key] = _Item(key, label, value, origin)
                return
        items[key] = _Item(key, label, "", "ask")

    propose(
        "config_path",
        "Path to Frigate's config.yml",
        o.frigate_config,
        [
            ("found", str(facts.config_file) if facts.config_file else ""),
            ("existing", str(ex_f.get("config_path") or "")),
            ("guess", str(frigate_defaults.config_path)),
        ],
    )
    db_found = fd.first_existing_file(fd.host_db_candidates(facts.config_file, facts.db_path))
    propose(
        "db_path",
        "Path to Frigate's frigate.db",
        o.frigate_db,
        [
            ("existing", str(ex_f.get("db_path") or "")),
            ("found", str(db_found) if db_found else ""),
            ("guess", str(frigate_defaults.db_path)),
        ],
    )
    rec_candidates: list[Path] = []
    if env.get("FRIGATE_RECORDINGS"):
        rec_candidates.append(Path(env["FRIGATE_RECORDINGS"]))
    if facts.config_file is not None:
        rec_candidates += [
            facts.config_file.parent / "media",
            facts.config_file.parent.parent / "media",
        ]
    rec_found = ""
    for cand in rec_candidates:
        res = fd.check_recordings_root(cand)
        if res.status == "ok":
            rec_found = str(res.path)
            break
    propose(
        "recordings_path",
        "Host-side Frigate media folder (the one that holds recordings/)",
        o.recordings_path,
        [
            ("existing", str(ex_f.get("recordings_path") or "")),
            ("found", rec_found),
            ("ask", ""),
        ],
    )
    if items["recordings_path"].origin == "ask":
        items["recordings_path"].value = str(frigate_defaults.recordings_path)
    propose(
        "sidecar_db",
        "Sidecar SQLite DB path",
        o.sidecar_db,
        [
            ("existing", str(ex_s.get("db_path") or "")),
            ("default", str(sidecar_defaults.db_path)),
        ],
    )
    propose(
        "bind_host",
        "Bind host",
        o.bind_host,
        [
            ("existing", str(ex_s.get("bind_host") or "")),
            ("default", sidecar_defaults.bind_host),
        ],
    )
    propose(
        "bind_port",
        "Bind port",
        None if o.bind_port is None else str(o.bind_port),
        [
            ("existing", str(ex_s.get("bind_port") or "")),
            ("default", str(sidecar_defaults.bind_port)),
        ],
    )

    # -- confirm or edit ------------------------------------------------------------
    open_items = [i for i in items.values() if i.origin != "flag"]
    if interactive:
        # What cannot be known (a guess) is asked first, one by one ...
        for i in open_items:
            if i.origin in ("guess", "ask"):
                i.value = str(typer.prompt(i.label, default=i.value))
        # ... then everything found or defaulted is shown once to confirm.
        confident = [i for i in open_items if i.origin not in ("guess", "ask")]
        if confident:
            _echo("\nI will use:")
            for i in confident:
                _echo(f"  {i.label}: {i.value}  ({i.origin})")
            if not typer.confirm("Use these values?", default=True):
                for i in confident:
                    i.value = str(typer.prompt(i.label, default=i.value))
    else:
        for i in open_items:
            origin = "default" if i.origin in ("ask", "guess") else i.origin
            _echo(f"• assumed {i.label}: {i.value} ({origin})")

    # -- the recordings location: Frigate's paths are container paths ----------------
    rec = items["recordings_path"]
    while True:
        check = fd.check_recordings_root(Path(rec.value))
        if check.status == "ok" and check.path != Path(rec.value):
            _echo(f"• {check.message}")
            rec.value = str(check.path)
        if check.status == "ok" or not interactive or rec.origin == "flag":
            break
        _echo(f"⚠ {_check_dir_note(check)}", err=True)
        if check.status == "warn" and typer.confirm("Use it anyway?", default=True):
            break
        if check.status == "bad" and typer.confirm("Use it anyway?", default=False):
            break
        rec.value = str(typer.prompt(rec.label, default=rec.value))
    if check.status == "warn" and not interactive:
        _echo(f"⚠ Recordings path {check.path} {check.message}", err=True)

    # Frigate's media directory as the database records it (container path).
    media_path = facts.media_path
    db_host = Path(items["db_path"].value)
    if db_host.is_file():
        with contextlib.suppress(Exception):
            from marcellus import doctor as doctor_mod

            row = doctor_mod._newest_recording_row(db_host)  # noqa: SLF001
            if row is not None and (root := fd.media_root_of(row[0])):
                media_path = root

    cfg: dict[str, Any] = copy.deepcopy(existing)
    f_cfg = cfg.setdefault("frigate", {})
    s_cfg = cfg.setdefault("sidecar", {})
    if not isinstance(f_cfg, dict):
        f_cfg = cfg["frigate"] = {}
    if not isinstance(s_cfg, dict):
        s_cfg = cfg["sidecar"] = {}
    f_cfg.update(
        {
            "base_url": base_url,
            "proxy_base_url": signin_url,
            "verify_tls": verify_tls,
            "config_path": items["config_path"].value,
            "db_path": items["db_path"].value,
            "recordings_path": rec.value,
        }
    )
    if media_path != str(frigate_defaults.media_path) or "media_path" in f_cfg:
        f_cfg["media_path"] = media_path
    s_cfg.update(
        {
            "db_path": items["sidecar_db"].value,
            "bind_host": items["bind_host"].value,
            "bind_port": int(items["bind_port"].value),
        }
    )

    # -- optional push step ---------------------------------------------------------
    decision = _push_step(o, facts, ex_p, interactive)
    if decision is not None:
        push_cfg = cfg.get("push")
        if not isinstance(push_cfg, dict):
            push_cfg = cfg["push"] = {}
        push_cfg.pop("mqtt_username", None)
        push_cfg.update(decision.config)

    # Validate through the real settings model so a bad value fails here, not
    # at first server start.
    settings = Settings.model_validate(cfg)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False))
    _echo(f"Wrote {out_path}")
    for line in late_warnings:
        _echo(line.format(path=out_path), err=True)

    if decision is not None:
        _finish_push(decision, settings)

    # Sanity checks: warn, never fail -- the config may be written on a box
    # where Frigate isn't reachable yet (e.g. inside `docker run --rm`).
    try:
        resp = frigate_tls.get(
            settings.frigate.base_url.rstrip("/") + "/api/version",
            verify_tls=settings.frigate.verify_tls,
            timeout=5.0,
        )
        resp.raise_for_status()
        _echo(f"✓ Frigate reachable at {settings.frigate.base_url} ({resp.text.strip()})")
    except Exception as exc:  # noqa: BLE001 -- diagnostics only
        _echo(f"⚠ Could not reach Frigate at {settings.frigate.base_url}: {exc}", err=True)
    db = Path(str(f_cfg["db_path"]))
    if db.exists():
        _echo(f"✓ Frigate DB found at {db}")
    else:
        _echo(f"⚠ Frigate DB not found at {db} (check your mount/path)", err=True)
    rec_dir = Path(str(f_cfg["recordings_path"]))
    if rec_dir.is_dir():
        _echo(f"✓ Recordings path exists at {rec_dir}")
    else:
        _echo(
            f"⚠ Recordings path {rec_dir} does not exist (scrub cache would find nothing)",
            err=True,
        )


# -- push ------------------------------------------------------------------------------


def _restart_hint(target: ip.EnvTarget) -> str:
    if target.kind == "systemd":
        return "sudo systemctl restart marcellus"
    if target.kind == "docker":
        install = os.environ.get("INSTALL_DIR") or ip.DEFAULT_INSTALL_DIR
        return f"cd {install} && docker compose up -d"
    return "# restart Marcellus so it reads the new password"


def _push_step(
    o: InitOptions,
    facts: fd.FrigateFacts,
    ex_push: dict[str, Any],
    interactive: bool,
) -> ip.PushDecision | None:
    """Ask about push, settle the broker and the password's home. None = skip."""
    ex_enabled = bool(ex_push.get("enabled"))
    m = facts.mqtt
    if facts.found_anything and not m.enabled:
        _echo(
            "• Push alerts need MQTT, and MQTT is off in Frigate. Turn on the `mqtt:` section "
            "in Frigate's config, then run `fsc init --force` again. Skipping push."
        )
        return None
    if interactive:
        if not (o.enable_push or typer.confirm("Set up push alerts now?", default=ex_enabled)):
            return None
    elif not o.enable_push:
        if ex_enabled:
            _echo("• push alerts: keeping the settings already in the config")
        else:
            _echo(
                "• push alerts: not set up (add --enable-push, with --mqtt-password-file or "
                f"${ip.PASSWORD_ENV_VAR} when the broker needs a login)"
            )
        return None

    # Broker: flags, then Frigate's values, then the existing config.
    host = o.mqtt_host or m.host or str(ex_push.get("mqtt_host") or "") or None
    port = o.mqtt_port or m.port or (int(ex_push.get("mqtt_port") or 0) or None)
    user = o.mqtt_user if o.mqtt_user is not None else (m.user or ex_push.get("mqtt_username"))
    user = str(user) if user else None
    if host and not port:
        port = fd.FRIGATE_DEFAULT_MQTT_PORT
    flagged = o.mqtt_host is not None
    if m.unresolved:
        _echo(
            f"• Frigate's MQTT {', '.join(m.unresolved)} come from environment placeholders "
            "that init does not resolve."
        )
    if m.tls:
        _echo(
            "⚠ Frigate talks TLS to its broker. Marcellus connects in plain text, so push "
            "needs a plain listener on the broker (usually port 1883): set that port below.",
            err=True,
        )
    if interactive:
        if host and not flagged:
            who = f" as user {user}" if user else ""
            _echo(f"Broker as Frigate sees it (reachable from here too?): {host}:{port}{who}")
            if not typer.confirm("Use this broker?", default=True):
                host = None
        if not host:
            host = str(typer.prompt("MQTT broker host"))
            port = int(typer.prompt("MQTT broker port", default=port or 1883))
            answer = typer.prompt(
                "MQTT username (blank for none)", default=user or "", show_default=bool(user)
            )
            user = str(answer) or None
    if not host:
        _echo("• Push alerts: no broker address found; pass --mqtt-host. Skipping push.")
        return None

    needs_login = bool(user) or m.needs_login
    cfg: dict[str, object] = {"enabled": True, "mqtt_host": host, "mqtt_port": int(port or 1883)}
    if user:
        cfg["mqtt_username"] = user
    if m.topic_prefix and m.topic_prefix != fd.FRIGATE_DEFAULT_TOPIC_PREFIX:
        cfg["mqtt_topic_reviews"] = f"{m.topic_prefix}/reviews"
        cfg["mqtt_topic_available"] = f"{m.topic_prefix}/available"
        cfg["mqtt_topic_events"] = f"{m.topic_prefix}/events"
    if m.client_id == "marcellus-push":
        _echo(
            "⚠ Frigate's own MQTT client_id is marcellus-push; give one of them another id.",
            err=True,
        )

    target = ip.detect_target(o.env_file)
    decision = ip.PushDecision(config=cfg, target=target)
    if not needs_login:
        _echo("• The broker needs no login; no password to store.")
        return decision

    # Where might a password already be?
    stored = ip.read_secret(target.path) if target.path is not None else None
    existing_pw = stored or os.environ.get(ip.ENV_KEY) or None
    new_pw: str | None = os.environ.get(ip.PASSWORD_ENV_VAR) or None
    try:
        if o.mqtt_password_file:
            new_pw = ip.read_password_file(o.mqtt_password_file)
    except ip.EnvFileError as exc:
        _echo(f"⚠ {exc}", err=True)
    can_store = ip.can_store(target)

    if existing_pw:
        # Never overwritten without an explicit yes.
        decision.password_for_test = existing_pw
        where = target.label if stored else "the environment"
        replace = False
        if interactive and stored and can_store:
            replace = bool(
                typer.confirm(
                    f"A password is already stored in {where}. Replace it?", default=False
                )
            )
        if not replace:
            note = "keeping it (not overwritten)" if new_pw else "keeping it"
            _echo(f"• An MQTT password is already set in {where}: {note}.")
            return decision
        new_pw = new_pw or _ask_password()
        if new_pw is None:
            return decision
    elif new_pw is None:
        if not interactive:
            _echo(
                "• Push alerts: the broker needs a login and no password was given "
                f"(--mqtt-password-file or ${ip.PASSWORD_ENV_VAR}). Skipping push."
            )
            return None
        if not can_store:
            _hand_over(decision, target)
            return decision
        new_pw = _ask_password()
        if new_pw is None:
            _echo('• No password entered: add it later (see the guide\'s "Set up push" page).')
            return decision

    decision.password_for_test = new_pw
    if can_store:
        decision.password_to_store = new_pw
    else:
        _hand_over(decision, target)
    return decision


def _ask_password() -> str | None:
    value = typer.prompt(
        "MQTT password (typing is hidden; blank to add it later)",
        hide_input=True,
        default="",
        show_default=False,
    )
    return str(value) or None


def _hand_over(decision: ip.PushDecision, target: ip.EnvTarget) -> None:
    why = {
        "docker": "init runs inside the container and cannot reach the install directory's .env",
        "systemd": "this is not root, and the file is root-owned",
        "file": "that file is not writable here",
    }[target.kind]
    cmds = ip.host_commands(target, _restart_hint(target))
    decision.follow_up = [
        f"The password was not stored ({why}). Store it yourself, where Marcellus reads it:",
        *[f"    {c}" for c in cmds],
    ]


def _finish_push(decision: ip.PushDecision, settings: Any) -> None:
    from marcellus import doctor as doctor_mod

    target = decision.target
    if decision.password_to_store is not None and target.path is not None:
        try:
            ip.write_secret(
                target.path, decision.password_to_store, private=target.kind == "systemd"
            )
            _echo(f"✓ MQTT password saved to {target.path} (mode 0600, not in sidecar.yml)")
            hint = _restart_hint(target)
            _echo(
                "  Restart Marcellus so it reads it."
                if hint.startswith("#")
                else f"  Restart Marcellus so it reads it: {hint}"
            )
        except ip.EnvFileError as exc:
            _echo(f"⚠ {exc}", err=True)
            _hand_over(decision, target)
    for line in decision.follow_up:
        _echo(line)

    pw = decision.password_for_test
    needs_login = bool(settings.push.mqtt_username)
    if needs_login and pw is None:
        _echo(
            "• MQTT connection not tested: no password available here yet. "
            "Run `fsc doctor` after storing it."
        )
        return
    try:
        if pw is not None:
            settings.push.mqtt_password = pw
        ctx = doctor_mod.Context(
            settings, timeout=5.0, mqtt_wait=8.0, extra_secrets=(pw,) if pw else ()
        )
        result = doctor_mod.check_mqtt(ctx)
        mark = {"pass": "✓", "warn": "⚠", "fail": "✗"}.get(result.status, "•")
        _echo(f"{mark} MQTT: {ctx.scrub(result.detail)}", err=result.status != "pass")
        if result.fix:
            _echo(f"  fix: {ctx.scrub(result.fix)}", err=True)
    except Exception as exc:  # noqa: BLE001 -- never let a probe crash init (or print locals)
        _echo(f"⚠ MQTT connection test could not run ({type(exc).__name__})", err=True)
